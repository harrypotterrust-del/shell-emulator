"""Исключения, которыми команды сообщают оболочке о своём результате."""


class CommandError(Exception):
    """Ошибка выполнения команды (например, неверные аргументы).

    Текст может состоять из нескольких строк - по одной на ошибку;
    оболочка добавит к каждой имя команды. В ``output`` команда
    передаёт то, что успела вывести до ошибки.
    """

    def __init__(self, message, output=None):
        """Сохранить текст ошибки ``message`` и частичный вывод."""
        super().__init__(message)
        self.output = output


class ExitRequest(Exception):
    """Запрос на завершение работы эмулятора с кодом возврата."""

    def __init__(self, code):
        """Сохранить код возврата ``code``."""
        super().__init__(code)
        self.code = code


def finish(output, errors):
    """Вернуть вывод команды или сообщить об ошибках вместе с ним.

    Команды, обрабатывающие несколько операндов, продолжают работу
    после ошибки одного из них: успешный вывод печатается, а ошибки
    собираются в одно исключение.
    """
    if errors:
        raise CommandError("\n".join(errors), output=output)
    return output
